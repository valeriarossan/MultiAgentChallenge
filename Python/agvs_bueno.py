UL_AREAS_SET = set(UL_AREAS)  # lookup O(1)

# FUNCIÓN A* - AHORA LAS CELDAS U/L (6) SE TRATAN COMO BLOQUEADAS
# A MENOS QUE SEAN EXACTAMENTE EL DESTINO DE ESTA BÚSQUEDA.
# ESTO EVITA QUE UN AGV "DE PASO" ATRAVIESE UNA ZONA DE CARGA/DESCARGA
# QUE NO ES SU MISIÓN ACTUAL, SIN IMPORTAR DESDE QUÉ LADO SE ACCEDA.
def astar(start, goal, graph=MOVEMENT_GRAPH, blocked=None):
    if start == goal:
        return [start]

    blocked = blocked or set() # Si no se proporcionó un conjunto de bloqueos,
                                # lo convierte en un conjunto vacío

    # Contiene las u/l areas y las estaciones de carga, las cuales no se pueden
    # atravesar a menos de ser el destino final
    RESTRICTED_UNLESS_GOAL = UL_AREAS_SET | set(CHARGING_STATIONS)

    def is_passable(cell):
        if cell in RESTRICTED_UNLESS_GOAL and cell != goal: # Si la celda está restringida y no es el destino, no
            return False
        return True # Si la celda es el destino, o no está restringida, puede pasar

    open_set = [(manhattan(start, goal), 0, start)] # nodos por explorar
    came_from = {}        # de qué nodo se viene, permite reconstruir el camino
    g_score = {start: 0}  # costo real acumulado desde el inicio hasta cada celda
    visited = set()       # celdas que ya fueron procesadas para no rehacerlo

    while open_set:           # mientras existan nodos pendientes por explorar
        _, cost, current = heapq.heappop(open_set)  # heap saca el elemento con menor prioridad

        if current == goal:   # Si se llegó al destino
            path = [current]
            while current in came_from: # Reconstruye el camino
                current = came_from[current]
                path.append(current)
            path.reverse()
            return path # Lo devuelve en orden

        if current in visited: # Si ya se visitó esa celda la salta
            continue
        visited.add(current) # Si no la marca como visitada

        for neighbor in graph.get(current, []): # Desde la celda actual, a qué celdas puede moverse?
            if not is_passable(neighbor): # Filtra movimientos inválidos
                continue
            if neighbor in blocked and neighbor != goal:
                continue

            # Calcula el nuevo costo
            tentative_g = cost + 1   # Cada movimiento cuesta 1
            if tentative_g < g_score.get(neighbor, float("inf")): # Se llegó a este vecino con un costo menor que el que se conocía anteriormente??
                g_score[neighbor] = tentative_g # Cuánto costó llegar
                came_from[neighbor] = current   # Desde dónde
                f_score = tentative_g + manhattan(neighbor, goal) # Fórmula clásica de A*
                heapq.heappush(open_set, (f_score, tentative_g, neighbor)) # Agrega el vecino a los nodods que A* debe explorar
                # Los nodos con menor f_score tienen prioridad

    return None #Si no existe ningún camino

