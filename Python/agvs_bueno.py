# ATRIBUTOS:  LOS DE RESOURCE AGENT + PALLET ID
class RackAgent(ResourceAgent):
    kind = "rack"

    def __init__(self, model, position):
        super().__init__(model, position)
        self.pallet_id = None

    # ¿ESTÁ OCUPADO EL RACK?
    def is_occupied(self):
        return self.pallet_id is not None

    # UN RACK CON PALLET NO SIRVE COMO DESTINO, AUNQUE SU STATUS DIGA "available"
    def is_available(self):
        return self.pallet_id is None and self.status == "available"

    def is_available_for(self, mission_id=None):
        if self.pallet_id is not None:
            return False
        return super().is_available_for(mission_id)

    # GUARDA UN PALLET EN EL RACK Y CIERRA LA RESERVA
    def store(self, pallet):
        self.pallet_id = pallet.pallet_id
        self.status = "occupied"
        self.reserved_by_mission = None
        pallet.status = "stored"

    # UN RACK REPARADO QUE CONSERVA SU PALLET VUELVE A "occupied", NO A "available"
    def repair(self):
        super().repair()
        if self.pallet_id is not None:
            self.status = "occupied"

    # AL SOLTAR LA RESERVA, UN RACK QUE TODAVÍA TIENE PALLET DEBE VOLVER A "occupied",
    # NO A "available". IMPORTA AL CANCELAR UNA MISIÓN TIPO 2 (RACK -> DOCK).
    def release(self, mission_id=None):
        ok = super().release(mission_id)
        if ok and self.pallet_id is not None and self.status == "available":
            self.status = "occupied"
        return ok

    # SACA EL PALLET DEL RACK Y LO DEVUELVE AL POOL DE DISPONIBLES
    def clear(self):
        self.pallet_id = None
        self.status = "available"
        self.reserved_by_mission = None


