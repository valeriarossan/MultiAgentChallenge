# FUNCIÓN: RESOLVE_OPERATIONAL_CELL
# DESCRIPCIÓN: DADA LA POSICIÓN LÓGICA DE UN RECURSO (RACK, LÍNEA, DOCK), DEVUELVE LA CELDA
# TRANSITABLE DESDE LA QUE UN AGV PUEDE OPERARLO. SI EL RECURSO YA ESTÁ SOBRE UNA CELDA
# TRANSITABLE (CASO DE LAS LÍNEAS DE PRODUCCIÓN), SE DEVUELVE ESA MISMA CELDA.
# NOTA: AHORA ES UNA FUNCIÓN GLOBAL, NO UN MÉTODO DEL MODELO, PORQUE SE NECESITA AL
# CONSTRUIR LOS RECURSOS, ANTES DE QUE EXISTAN LAS MISIONES.
def resolve_operational_cell(target):
    if target in MOVEMENT_GRAPH:
        return target
    x, y = target
    candidatos = [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    # PRIORIDAD: SOLO SE OPERA UN RECURSO DESDE SU ZONA DE CARGA/DESCARGA (6)
    for c in candidatos:
        if c in MOVEMENT_GRAPH and LAYOUT_INFO[c[1]][c[0]] == 6:
            return c
    return None


# FUNCIÓN: COMPUTE_OPERABLE_CELLS
# DESCRIPCIÓN: A* TRATA LAS ZONAS U/L Y LOS CARGADORES COMO INTRANSITABLES SALVO QUE SEAN
# EL DESTINO. ESO SIGNIFICA QUE UNA CELDA U/D EN MEDIO DE UNA COLUMNA DE U/L NUNCA ES
# ALCANZABLE: PARA LLEGAR HABRÍA QUE ATRAVESAR OTRA U/L QUE NO ES EL DESTINO.
# EN ESTE LAYOUT ESO DEJA 8 RACKS INALCANZABLES (LOS DE EN MEDIO DE LAS COLUMNAS DE 4).
# ESTA FUNCIÓN LOS DETECTA UNA SOLA VEZ AL ARRANCAR, PARA QUE EL MODELO NUNCA PUBLIQUE
# UNA MISIÓN IMPOSIBLE. SIN ESTO, UN AGV ACEPTA LA MISIÓN, NO ENCUENTRA RUTA NUNCA Y SE
# QUEDA CONGELADO CON EL PALLET ENCIMA PARA SIEMPRE.
def compute_operable_cells():
    from collections import deque

    restricted = UL_AREAS_SET | set(CHARGING_STATIONS)
    libres = {c for c in MOVEMENT_GRAPH if c not in restricted}

    # COMPONENTE CONEXA DEL PISO LIBRE
    inicio = None
    for c in libres:
        inicio = c
        break

    comp = set()
    if inicio is not None:
        comp.add(inicio)
        cola = deque([inicio])
        while cola:
            c = cola.popleft()
            for n in MOVEMENT_GRAPH[c]:
                if n in libres and n not in comp:
                    comp.add(n)
                    cola.append(n)

    operables = set(comp)
    for c in MOVEMENT_GRAPH:
        if c in comp:
            continue
        # UNA CELDA RESTRINGIDA ES OPERABLE SI SE PUEDE ENTRAR Y SALIR DE ELLA
        # DESDE EL PISO LIBRE EN UN SOLO PASO
        entra = any(c in MOVEMENT_GRAPH[n] for n in comp)
        sale = any(n in comp for n in MOVEMENT_GRAPH.get(c, []))
        if entra and sale:
            operables.add(c)

    return operables

OPERABLE_CELLS = compute_operable_cells()


