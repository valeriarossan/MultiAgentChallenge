# CLASE:      RESOURCE AGENT  (CLASE BASE NUEVA)
# DESCRIPCIÓN: TODO ELEMENTO FIJO DEL ALMACÉN CON EL QUE UNA MISIÓN PUEDE INTERACTUAR:
# RACKS, LÍNEAS DE PRODUCCIÓN Y TRUCK DOCKS. TENER UNA BASE COMÚN PERMITE QUE
# out_of_service, LAS RESERVAS Y LOS FILTROS DE spawn_mission SEAN UN SOLO CAMINO DE
# CÓDIGO EN LUGAR DE TRES.
# ATRIBUTOS:
#   position      -> POSICIÓN LÓGICA DEL RECURSO EN EL GRID (LA CELDA QUE SE DIBUJA)
#   access_cell   -> CELDA TRANSITABLE DESDE LA QUE UN AGV LO OPERA (DESTINO REAL DE A*)
#   status        -> available | occupied | is_reserved | out_of_service
#   reserved_by_mission -> ID DE LA MISIÓN QUE LO TIENE APARTADO (None SI NINGUNA)
class ResourceAgent(mesa.Agent):
    kind = "resource"

    def __init__(self, model, position):
        super().__init__(model)
        self.position = position
        self.access_cell = resolve_operational_cell(position)
        self.status = "available"
        if self.access_cell is None or self.access_cell not in OPERABLE_CELLS:
            self.status = "unreachable"   # NINGÚN AGV PUEDE LLEGAR: QUEDA FUERA DEL JUEGO
        self.reserved_by_mission = None
        self.repair_at_step = None          # STEP EN EL QUE VUELVE A SERVICIO
        self.status_before_failure = None   # STATUS AL QUE REGRESA TRAS LA REPARACIÓN

    # ¿EL RECURSO ESTÁ OPERATIVO? (NI AVERIADO NI INALCANZABLE)
    def is_usable(self):
        return self.status not in ("out_of_service", "unreachable")

    # ¿ESTE RECURSO PUEDE USARSE PARA UNA MISIÓN NUEVA?
    def is_available(self):
        return self.status == "available"

    # ¿ESTE RECURSO ESTÁ DISPONIBLE PARA ESTA MISIÓN EN CONCRETO?
    # (SI YA ESTÁ RESERVADO POR ESA MISMA MISIÓN, SIGUE SIENDO SUYO)
    def is_available_for(self, mission_id=None):
        if self.status == "available":
            return True
        if mission_id is not None and self.reserved_by_mission == mission_id:
            return True
        return False

    # ¿ESTÁ FUERA DE SERVICIO?
    def is_out_of_service(self):
        return self.status == "out_of_service"

    # PONE EL RECURSO FUERA DE SERVICIO Y GUARDA EL ESTADO AL QUE DEBERÁ VOLVER
    def set_out_of_service(self, repair_at_step):
        self.status_before_failure = self.status
        self.status = "out_of_service"
        self.repair_at_step = repair_at_step
        self.reserved_by_mission = None   # LAS MISIONES AFECTADAS SE RE-PLANEAN APARTE

    # DEVUELVE EL RECURSO A SERVICIO
    def repair(self):
        self.status = "available"
        self.repair_at_step = None
        self.status_before_failure = None

    # APARTA EL RECURSO PARA UNA MISIÓN
    def reserve_for(self, mission):
        self.status = "is_reserved"
        self.reserved_by_mission = mission.id

    # LIBERA LA RESERVA. SOLO LA LIBERA SI LA MISIÓN QUE PIDE ES LA DUEÑA, PARA QUE UNA
    # MISIÓN NO PUEDA SOLTAR POR ERROR EL RECURSO DE OTRA.
    def release(self, mission_id=None):
        if mission_id is not None and self.reserved_by_mission != mission_id:
            return False
        self.reserved_by_mission = None
        if self.status == "is_reserved":
            self.status = "available"
        return True


