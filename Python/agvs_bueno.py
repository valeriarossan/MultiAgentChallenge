# GRAFO DE MOVIMIENTO
# Se construye una sola vez con el layout estático. Respeta:
#  - obstáculos fijos (racks, líneas de producción, docks, puertas)
#  - carriles de un solo sentido (7: solo izquierda / 8: solo derecha)
