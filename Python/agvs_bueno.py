import heapq

def is_walkable(cell): # Esta celda puede usarse para desplazarse?
    x, y = cell
    val = LAYOUT_INFO[y][x]
    return val in (0, 4, 6, 7, 8, 9, 10)  # SE AGREGAN 9 Y 10

def build_movement_graph():
    graph = {}

    for y in range(GRID_H):
        for x in range(GRID_W):
            cell = (x, y)
            if is_walkable(cell):   # Si es transitable
                graph[cell] = []    # Agrega la celda como nodo del grafo

    for (x, y) in graph: # Recorre todas las celdas consideradas transitables
        val = LAYOUT_INFO[y][x]    # A cuál de mis vecinos puedo moverme?

        # VERTICAL: BLOQUEADO SI VAL O VECINO ES 10 (solo-abajo, bloquea subir)
        up = (x, y - 1) # subir
        if up in graph:
            up_val = LAYOUT_INFO[y - 1][x] # Obtiene el tipo de celda
            if val != 10 and up_val != 10: # Solo se mueve hacia arriba si la actual y la de arriban no son 10
                graph[(x, y)].append(up)

        # VERTICAL: BLOQUEADO SI VAL O VECINO ES 9 (solo-arriba, bloquea bajar)
        down = (x, y + 1) # bajar
        if down in graph:
            down_val = LAYOUT_INFO[y + 1][x]
            if val != 9 and down_val != 9:
                graph[(x, y)].append(down)

        # HORIZONTAL: derecha
        right = (x + 1, y)
        if right in graph:
            right_val = LAYOUT_INFO[y][x + 1]
            # REGLA ORIGINAL
            ok = val not in (7, 9, 10) and right_val not in (7, 9, 10)
            # EXCEPCIÓN: U/L puede conectar lateralmente con el shaft adyacente
            # Esto permite al AGV entrar/salir del shaft hacia su access cell interior
            if not ok:
                ok = (val == 6 and right_val in (9, 10)) or (val in (9, 10) and right_val == 6)
            if ok:
                graph[(x, y)].append(right)

        # HORIZONTAL: izquierda  (misma excepción)
        left = (x - 1, y)
        if left in graph:
            left_val = LAYOUT_INFO[y][x - 1]
            ok = val not in (8, 9, 10) and left_val not in (8, 9, 10)
            if not ok:
                ok = (val == 6 and left_val in (9, 10)) or (val in (9, 10) and left_val == 6)
            if ok:
                graph[(x, y)].append(left)

    return graph

MOVEMENT_GRAPH = build_movement_graph()

